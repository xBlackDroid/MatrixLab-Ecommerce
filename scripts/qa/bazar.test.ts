import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { applyCommand, emptyBazar, envelopeSchema, pesos, type Command } from "../../src/lib/bazar/domain";

let state = emptyBazar();
const now = "2026-10-31T19:00:00.000Z";
const run = (command: Command, id = randomUUID()) => { state = applyCommand(state, id, command, now); return id; };
const item = run({ kind: "item", name: "Gorra", sku: "GO001", priceCents: 27900, quantity: 2 });
const saleCommand: Command = { kind: "sale", method: "efectivo", notes: "Promoción", lines: [{ itemId: item, quantity: 1, priceCents: 25000 }] };
const sale = run(saleCommand);
assert.equal(state.items[0].stock, 1);
assert.equal(state.sales[0].totalCents, 25000);
assert.equal(state.sales[0].lines[0].name, "Gorra");
const before = structuredClone(state);
run(saleCommand, sale);
assert.deepEqual(state, before, "network retry must not duplicate sales");
assert.throws(() => run({ ...saleCommand, notes: "Different" }, sale), /otra operación/);
assert.throws(() => run({ ...saleCommand, lines: [{ itemId: item, quantity: 2, priceCents: 25000 }] }), /Existencia insuficiente/);
assert.throws(() => run({ ...saleCommand, lines: [...saleCommand.lines, ...saleCommand.lines] }), /dos veces/);
assert.deepEqual(state, before, "failed sale must not mutate state");
run({ kind: "void", saleId: sale, reason: "Error de captura" });
assert.equal(state.items[0].stock, 2);
assert.equal(state.sales[0].voidReason, "Error de captura");
assert.throws(() => run({ kind: "void", saleId: sale, reason: "Otro" }), /ya está anulada/);
run({ kind: "stock", itemId: item, quantity: 3 });
assert.equal(state.items[0].stock, 5);
assert.equal(state.items[0].brought, 5);
assert.throws(() => run({ kind: "item", name: "Otra", sku: "go001", quantity: 1, priceCents: 100 }), /ya existe/);
const id = run({ ...saleCommand, lines: [{ itemId: item, quantity: 5, priceCents: 27900 }] });
assert.equal(state.items[0].stock, 0);
assert.throws(() => run(saleCommand), /Existencia insuficiente/);
assert.equal(state.sales.find(s => s.id === id)?.totalCents, 139500);
assert.equal(pesos("279.99"), 27999);
assert.throws(() => pesos("1.999"));
assert.throws(() => pesos("-5"));
assert.equal(envelopeSchema.safeParse({ date: "2026-02-30", requestId: randomUUID(), command: saleCommand }).success, false);
assert.equal(envelopeSchema.safeParse({ date: "2026-10-31", requestId: randomUUID(), command: { ...saleCommand, lines: [{ itemId: item, quantity: -1, priceCents: 500 }] } }).success, false);
console.log("PASS bazar: stock, promotional prices, void/restock, atomic failures, retry idempotency, duplicate codes, sold-out protection and validation.");
